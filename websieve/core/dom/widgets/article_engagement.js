function articleReactionChip(node) {
  if (!node || !node.matches) return false;
  var icon = normalizeText(node.getAttribute("data-icon") || "").toLowerCase();
  if (!icon || node.querySelector("a[href], button, p, article, section, video, audio, form, input")) return false;

  var text = normalizeText(node.textContent || "");
  if (!text || text.length > 40 || !/^(?:like|love|angry|sad|wow|haha|lubię to|zły|super|szok|smutny)$/i.test(text)) return false;
  var images = Array.from(node.querySelectorAll("img"));
  if (images.length !== 1 || node.children.length > 3) return false;
  var image = images[0];
  var imageSignal = normalizeText([image.getAttribute("alt"), image.getAttribute("src")].filter(Boolean).join(" ")).toLowerCase();
  return imageSignal.indexOf(icon) >= 0 || /(?:emotion|reaction)[/_.-]/i.test(imageSignal);
}

function articleSyntheticAudioNotice(node) {
  if (!node || !node.matches) return false;
  var tokens = articleWidgetTokens(node);
  if (tokens.indexOf("audio") === -1) return false;
  if (node.querySelector("a[href], button, input, audio, video, iframe, object, embed, img, picture, figure, pre, code, table, ul, ol")) return false;

  var articlePlayer = tokens.indexOf("article") >= 0 || tokens.indexOf("player") >= 0;
  var plainNotice = node.matches("div, span") && Array.from(node.querySelectorAll("*")).every(function(child) {
    return child.matches("div, span");
  });
  if (articlePlayer && plainNotice &&
      /^Ascolta l['\u2019]articolo\s+\d+\s+min(?:uti)?\s+Questo audio \u00e8 generato in automatico\.?$/i.test(normalizeText(node.textContent))) return true;

  if (tokens.indexOf("player") === -1) return false;
  var lines = Array.from(node.querySelectorAll("p, span, div")).filter(function(child) {
    return !child.querySelector("p, span, div");
  }).map(function(child) { return normalizeText(child.textContent || ""); }).filter(Boolean);
  if (lines.length < 2 || lines.length > 4) return false;
  var text = lines.join(" ");
  var prompt = /(?:^|\s)(?:listen to (?:this |the )?(?:article|story)|odsłuchaj artykuł)(?:\s|$)/i.test(text);
  var duration = /(?:^|\s)\d{1,3}:\d{2}(?:\s*(?:min|minutes?|sek|seconds?))?(?:\s|$)/i.test(text);
  var synthetic = /\b(?:audio (?:is |was )?generated by ai|audio generowane przez ai)\b/i.test(text);
  return prompt && duration && synthetic;
}
